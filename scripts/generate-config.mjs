import { writeFile } from "node:fs/promises";

const apiBase = (process.env.API_BASE_URL || "http://localhost:4000/api").replace(/\/$/, "");

await writeFile(
  new URL("../frontend/config.js", import.meta.url),
  `// Generated by scripts/generate-config.mjs — do not edit by hand.\nwindow.CODEBLOOM_CONFIG = Object.freeze({ API_BASE: ${JSON.stringify(apiBase)} });\n`
);
